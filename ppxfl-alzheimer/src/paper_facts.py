"""
paper_facts.py — the numbers the paper's prose quotes, as LaTeX macros.

The tables are generated by ``paper_tables_v3``; this writes the
``% BEGIN AUTO:current-facts`` block of macros that the abstract, results and
conclusion use in running text, so no figure in prose is typed by hand.

"Current" is the v6 representation (deepmriprep region volumes) on the 799
subjects. v4 (760 subjects, the earlier features) and v3 (297 subjects) are
read for the cohort-growth comparison, and v5 (799 subjects, earlier features)
for the feature comparison, since both are reported results in their own right.
"""

from __future__ import annotations

import argparse
import json
import os
from collections import defaultdict

from .paper_tables_v3 import replace_block


def _load(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def _mean(entry):
    return entry["mean"] if isinstance(entry, dict) else entry


def best(conditions, label_set, split="subject"):
    """The most accurate centralised model for a task and split."""
    return max((c for c in conditions if c["family"] == "centralised"
                and c["label_set"] == label_set and c["split_scheme"] == split),
               key=lambda c: _mean(c["accuracy"]))


def one(conditions, **query):
    return next(c for c in conditions if all(c.get(k) == v for k, v in query.items()))


def pct(value):
    return f"{value * 100:.1f}\\%"


def pts(after, before):
    return f"{(after - before) * 100:.1f}"


def balanced_cohort(directory):
    """Best subject-disjoint accuracy and cohort size on the sex-balanced design."""
    runs = defaultdict(list)
    sizes = {}
    for name in os.listdir(directory):
        if not name.endswith(".json") or name == "centralised_summary.json":
            continue
        run = _load(os.path.join(directory, name))
        if run["split_scheme"] == "subject":
            runs[(run["model"], run["label_set"])].append(run["overall"]["accuracy"])
            sizes[run["label_set"]] = run["n_subjects"]
    means = {key: sum(v) / len(v) for key, v in runs.items()}
    top = {ls: max(m for (_, label), m in means.items() if label == ls) for ls in sizes}
    return top, sizes


def facts(root: str) -> dict[str, str]:
    v6 = os.path.join(root, "results_v6")
    imaging = _load(os.path.join(v6, "results_summary_v6_imaging_only.json"))["conditions"]
    full = _load(os.path.join(v6, "results_summary_v6.json"))["conditions"]
    v5 = _load(os.path.join(root, "results_v5", "results_summary_v5.json"))["conditions"]
    v4 = _load(os.path.join(root, "results_v4", "results_summary_v4.json"))["conditions"]
    v3 = _load(os.path.join(root, "results_v3", "results_summary_v3.json"))["conditions"]
    confounds = _load(os.path.join(v6, "metrics", "confounds.json"))
    law = _load(os.path.join(v6, "metrics", "dimension_law.json"))["rows"]
    partition = _load(os.path.join(v6, "metrics", "dp_cn-mci-ad_eps1.0_s42.json"))["partition"]
    attacks = defaultdict(list)
    for run in _load(os.path.join(v6, "metrics", "mia_v3.json"))["runs"]:
        attacks[run["target_epsilon"]].append(run["attack_auroc"])
    balanced, balanced_n = balanced_cohort(os.path.join(v6, "metrics_balanced"))

    tri, bin_ = best(imaging, "cn-mci-ad"), best(imaging, "cn-ad")
    private = {eps: one(full, family="privacy", label_set="cn-ad", target_epsilon=eps)
               for eps in (None, 1.0, 10.0)}
    dimension = one(law, model="roi_logreg", target_epsilon=1.0)["dimension"]

    def fed(conditions, label_set):
        return _mean(one(conditions, family="federated", label_set=label_set,
                         split_scheme="subject", client_scheme="natural")["accuracy"])

    def gap(conditions, label_set):
        """Points lost by holding whole sites out (best model under each protocol)."""
        return pts(_mean(best(conditions, label_set)["accuracy"]),
                   _mean(best(conditions, label_set, "site")["accuracy"]))

    def dp_cost(conditions):
        p = {e: _mean(one(conditions, family="privacy", label_set="cn-ad",
                          target_epsilon=e)["accuracy"]) for e in (None, 1.0)}
        return pts(p[None], p[1.0])

    def xai(conditions, eps, key="explanation_agreement"):
        return _mean(one(conditions, family="privacy", label_set="cn-ad", target_epsilon=eps)[key])

    composition = confounds["cohort_composition"]
    per_class = {k: composition[f"{k}-F"] + composition[f"{k}-M"] for k in ("CN", "MCI", "AD")}
    conf = confounds["results"]
    bal = lambda ls, k: conf[ls][k]["balanced_accuracy"]["mean"]  # noqa: E731
    strata = confounds["stratified"]["cn-mci-ad"]

    return {
        # current cohort and representation (v6)
        "CohSubjects": str(tri["n_subjects"]),
        "CohSites": str(sum(len(c["sites"]) for c in partition["clients"])),
        "CohClients": str(partition["n_clients"]),
        "CohFeatures": str(dimension // 3 - 1),
        "CohDim": str(dimension),
        "CohTriAcc": pct(_mean(tri["accuracy"])),
        "CohTriF": f"{_mean(tri['macro_f1']):.3f}",
        "CohTriAUROC": f"{_mean(tri['macro_auroc']):.3f}",
        "CohTriSite": pct(_mean(best(imaging, "cn-mci-ad", "site")["accuracy"])),
        "CohBinAcc": pct(_mean(bin_["accuracy"])),
        "CohBinSite": pct(_mean(best(imaging, "cn-ad", "site")["accuracy"])),
        "CohBinAUROC": f"{_mean(bin_['macro_auroc']):.3f}",
        "CohBinCov": pct(_mean(best(full, "cn-ad")["accuracy"])),
        "CohFedTri": pct(fed(full, "cn-mci-ad")),
        "CohFedBin": pct(fed(full, "cn-ad")),
        "CohDpBinNone": pct(_mean(private[None]["accuracy"])),
        "CohDpBinOne": pct(_mean(private[1.0]["accuracy"])),
        "CohDpBinTen": pct(_mean(private[10.0]["accuracy"])),
        "CohXaiNonPrivate": f"{xai(full, None):.3f}",
        "CohXaiTen": f"{xai(full, 10.0):.3f}",
        "CohMtNonPrivate": pct(xai(full, None, "medial_temporal_share")),
        "CohMtTen": pct(xai(full, 10.0, "medial_temporal_share")),
        "CohAttackNone": f"{sum(attacks[None]) / len(attacks[None]):.3f}",
        "CohAttackOne": f"{sum(attacks[1.0]) / len(attacks[1.0]):.3f}",
        "CohDemog": str(confounds["n_subjects"]),
        # demographics (balanced accuracy, as in the confounds table)
        "ConfSexTri": pct(bal("cn-mci-ad", "sex")),
        "ConfAgeTri": pct(bal("cn-mci-ad", "age")),
        "ConfImgTri": pct(bal("cn-mci-ad", "imaging")),
        "ConfImgDemoTri": pct(bal("cn-mci-ad", "imaging+demographics")),
        "ConfImgFemaleTri": pct(strata["F"]["balanced_accuracy"]["mean"]),
        "ConfImgMaleTri": pct(strata["M"]["balanced_accuracy"]["mean"]),
        "ConfNFemaleTri": str(strata["F"]["n"]),
        "ConfNMaleTri": str(strata["M"]["n"]),
        "ConfSexBin": pct(bal("cn-ad", "sex")),
        "ConfImgBin": pct(bal("cn-ad", "imaging")),
        "ConfChanceTri": pct(max(per_class.values()) / sum(per_class.values())),
        "ConfChanceBin": pct(max(per_class["CN"], per_class["AD"])
                             / (per_class["CN"] + per_class["AD"])),
        # the sex-balanced design
        "BalN": str(balanced_n["cn-mci-ad"]),
        "BalTri": pct(balanced["cn-mci-ad"]),
        "BalBin": pct(balanced["cn-ad"]),
        # cohort growth, same pipeline: v3 (297) against v4 (760)
        "VFourSubjects": str(best(v4, "cn-mci-ad")["n_subjects"]),
        "VFourTriAcc": pct(_mean(best(v4, "cn-mci-ad")["accuracy"])),
        "VFourBinAcc": pct(_mean(best(v4, "cn-ad")["accuracy"])),
        "VFourTriGap": gap(v4, "cn-mci-ad"),
        "VFourBinGap": gap(v4, "cn-ad"),
        "InitTriGap": gap(v3, "cn-mci-ad"),
        "InitBinGap": gap(v3, "cn-ad"),
        "VFourDpBinCost": dp_cost(v4),
        "InitDpBinCost": dp_cost(v3),
        "VFourXaiNonPrivate": f"{xai(v4, None):.3f}",
        "VFourXaiTen": f"{xai(v4, 10.0):.3f}",
        "VFourMtNonPrivate": pct(xai(v4, None, "medial_temporal_share")),
        "VFourMtTen": pct(xai(v4, 10.0, "medial_temporal_share")),
        # better features, same subjects: v5 against v6
        "VFiveTriAcc": pct(_mean(best(v5, "cn-mci-ad")["accuracy"])),
        "VFiveBinAcc": pct(_mean(best(v5, "cn-ad")["accuracy"])),
        "VFiveBinAUROC": f"{_mean(best(v5, 'cn-ad')['macro_auroc']):.3f}",
        "VFiveFedTri": pct(fed(v5, "cn-mci-ad")),
        "VFiveFedBin": pct(fed(v5, "cn-ad")),
        "VFiveDpBinOne": pct(_mean(one(v5, family="privacy", label_set="cn-ad",
                                       target_epsilon=1.0)["accuracy"])),
        "VFiveXaiTen": f"{xai(v5, 10.0):.3f}",
    }


def render(values: dict[str, str]) -> str:
    return "\n".join(f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in values.items())


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="write the paper's prose macros")
    parser.add_argument("--root", default=".")
    parser.add_argument("--paper", default=os.path.join("..", "paper.tex"))
    args = parser.parse_args(argv)
    with open(args.paper, encoding="utf-8") as handle:
        text = handle.read()
    text, found = replace_block(text, "current-facts", render(facts(args.root)))
    if not found:
        raise SystemExit("no '% BEGIN AUTO:current-facts' block in the paper")
    with open(args.paper, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote current-facts into {args.paper}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
